import { VaultCryptoError } from './errors';
import { cryptoKeyName, getKmsClient } from './kmsClient';

/**
 * Envelope encryption for the Photo Vault.
 *
 * The KEK lives in Cloud KMS and never leaves it. These helpers wrap and
 * unwrap a per-user Vault Key (the DEK that will encrypt photos on the
 * device with AES-256-GCM).
 *
 * INTERNAL ONLY. Nothing here is a callable function or an HTTP endpoint,
 * nothing takes a uid, and the mobile app can never reach it directly. A
 * future authenticated callable will own authorization and will be the only
 * caller (docs/20_backend_functions_photo_vault.md).
 *
 * Neither the Vault Key nor the wrapped key is ever logged, in whole or in
 * part — see the logging policy in lib/logger.ts.
 */

/** AES-256 ⇒ the Vault Key is exactly 32 bytes. Nothing else is accepted. */
export const VAULT_KEY_BYTES = 32;

/**
 * Defensive ceiling for a wrapped key. A KMS-wrapped 32-byte DEK is a few
 * hundred bytes; this only exists to reject absurd input before it reaches
 * KMS.
 */
const MAX_WRAPPED_KEY_BASE64_LENGTH = 4096;

function assertValidVaultKey(vaultKey: Uint8Array): void {
  if (!(vaultKey instanceof Uint8Array)) {
    throw new VaultCryptoError('INVALID_VAULT_KEY', 'vault key must be raw bytes');
  }
  if (vaultKey.length !== VAULT_KEY_BYTES) {
    // Length is shape information, not key material — safe to state.
    throw new VaultCryptoError(
      'INVALID_VAULT_KEY',
      `expected ${VAULT_KEY_BYTES} bytes, got ${vaultKey.length}`,
    );
  }
}

/** Strict base64 round-trip check: catches truncation and stray characters. */
function decodeWrappedKey(wrappedVaultKey: string): Buffer {
  if (typeof wrappedVaultKey !== 'string' || wrappedVaultKey.length === 0) {
    throw new VaultCryptoError('INVALID_WRAPPED_KEY', 'wrapped key must be a non-empty string');
  }
  if (wrappedVaultKey.length > MAX_WRAPPED_KEY_BASE64_LENGTH) {
    throw new VaultCryptoError('INVALID_WRAPPED_KEY', 'wrapped key exceeds the size limit');
  }

  const decoded = Buffer.from(wrappedVaultKey, 'base64');
  if (decoded.length === 0 || decoded.toString('base64') !== wrappedVaultKey) {
    throw new VaultCryptoError('INVALID_WRAPPED_KEY', 'wrapped key is not valid base64');
  }

  return decoded;
}

export interface WrappedVaultKey {
  /** Ciphertext, base64 — the exact form persisted in Firestore. */
  wrappedVaultKey: string;
  /**
   * Fully-qualified CryptoKeyVersion that produced the ciphertext, taken
   * from the KMS response (never inferred or hardcoded). Persisted for
   * auditing and to make a future rewrap possible.
   */
  kmsKeyVersion: string;
}

/**
 * Encrypts a Vault Key with the KMS-held KEK.
 *
 * @param vaultKey raw 32-byte DEK, generated by the caller with a CSPRNG.
 */
export async function wrapVaultKey(vaultKey: Uint8Array): Promise<WrappedVaultKey> {
  assertValidVaultKey(vaultKey);

  const name = cryptoKeyName();

  let response;
  try {
    [response] = await getKmsClient().encrypt({ name, plaintext: vaultKey });
  } catch {
    // The KMS error is deliberately not attached: it can carry project, key
    // and IAM details that must not travel further.
    throw new VaultCryptoError('KMS_ENCRYPT_FAILED', 'KMS rejected the encrypt request');
  }

  const ciphertext = response?.ciphertext;
  if (!ciphertext || ciphertext.length === 0) {
    throw new VaultCryptoError('KMS_ENCRYPT_FAILED', 'KMS returned an empty ciphertext');
  }

  // `EncryptResponse.name` is the CryptoKeyVersion actually used. Requiring
  // it both guards against a misrouted response and gives us the version to
  // persist — we never fabricate that value.
  const kmsKeyVersion = response?.name;
  if (!kmsKeyVersion || !kmsKeyVersion.startsWith(`${name}/cryptoKeyVersions/`)) {
    throw new VaultCryptoError('KMS_ENCRYPT_FAILED', 'KMS response key mismatch');
  }

  return {
    wrappedVaultKey: Buffer.from(ciphertext).toString('base64'),
    kmsKeyVersion,
  };
}

/**
 * Decrypts a wrapped Vault Key with the KMS-held KEK.
 *
 * @param wrappedVaultKey base64 ciphertext exactly as persisted.
 * @returns the raw 32-byte Vault Key. The caller is responsible for keeping
 *          it in memory only, and for zeroing the buffer when done.
 */
export async function unwrapVaultKey(wrappedVaultKey: string): Promise<Buffer> {
  const ciphertext = decodeWrappedKey(wrappedVaultKey);

  let response;
  try {
    [response] = await getKmsClient().decrypt({ name: cryptoKeyName(), ciphertext });
  } catch {
    throw new VaultCryptoError('KMS_DECRYPT_FAILED', 'KMS rejected the decrypt request');
  }

  const plaintext = response?.plaintext;
  if (!plaintext || plaintext.length === 0) {
    throw new VaultCryptoError('KMS_DECRYPT_FAILED', 'KMS returned an empty plaintext');
  }

  const vaultKey = Buffer.from(plaintext);
  // A correct unwrap can only ever yield a 32-byte key. Anything else means
  // the stored ciphertext does not hold what we think it holds — fail loudly
  // instead of handing back bytes nobody validated.
  if (vaultKey.length !== VAULT_KEY_BYTES) {
    throw new VaultCryptoError('KMS_DECRYPT_FAILED', 'unwrapped key has an unexpected length');
  }

  return vaultKey;
}
