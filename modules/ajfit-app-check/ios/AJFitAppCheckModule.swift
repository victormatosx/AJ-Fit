

import ExpoModulesCore
import FirebaseAppCheck
import FirebaseCore

enum AJFitAppCheckConfigurator {
  private static let configurationLock = NSLock()

  #if DEBUG
  private(set) static var debugProviderFactoryInstalledByAJFit = false
  #endif

  static func configureNativeFirebaseIfNeeded() {
    configurationLock.lock()
    defer { configurationLock.unlock() }

    guard FirebaseApp.app() == nil else { return }

    #if DEBUG
    if let pinnedToken = ajfitPinnedAppCheckDebugToken, !pinnedToken.isEmpty {
      setenv("AppCheckDebugToken", pinnedToken, 1)
    }
    AppCheck.setAppCheckProviderFactory(AppCheckDebugProviderFactory())
    debugProviderFactoryInstalledByAJFit = true
    #else
    AppCheck.setAppCheckProviderFactory(AppAttestProviderFactory())
    #endif

    FirebaseApp.configure()
    AppCheck.appCheck().isTokenAutoRefreshEnabled = false
  }
}

public final class AJFitAppCheckAppDelegateSubscriber: ExpoAppDelegateSubscriber {
  @MainActor
  public func appDelegateWillBeginInitialization() {
    AJFitAppCheckConfigurator.configureNativeFirebaseIfNeeded()
  }
}

public final class AJFitAppCheckModule: Module {

  public func definition() -> ModuleDefinition {
    Name("AJFitAppCheck")

    OnCreate {
      AJFitAppCheckConfigurator.configureNativeFirebaseIfNeeded()
    }

    AsyncFunction("getAppCheckToken") { (forceRefresh: Bool, promise: Promise) in
      AJFitAppCheckConfigurator.configureNativeFirebaseIfNeeded()

      // Defensive/diagnostic only — `configureNativeFirebaseIfNeeded()` above
      // is the sole place `FirebaseApp.configure()` is ever called in this
      // codebase (guarded, idempotent, provider-factory-set-before-configure).
      // In practice this should never be nil by this point; if it somehow is
      // (e.g. a future change adds a second `FirebaseApp.configure()` call
      // elsewhere and races this one), fail with a distinct, greppable code
      // instead of letting `AppCheck.appCheck()` hit its own internal
      // "not configured" fatal path with zero diagnostic value on the JS side.
      guard FirebaseApp.app() != nil else {
        promise.reject(
          "ERR_APP_CHECK_NOT_CONFIGURED",
          "FirebaseApp.app() is nil after configureNativeFirebaseIfNeeded() — native Firebase was never configured."
        )
        return
      }

      #if DEBUG
      // `ajfitPinnedAppCheckDebugToken` comes from a file GENERATED by the
      // `app-check-debug-token` Expo config plugin at `expo prebuild` time
      // (ios/AJFit/AJFitAppCheckDebugTokenLocal.swift, gitignored, never
      // committed) — never hand-written here. That whole generated file is
      // itself wrapped in `#if DEBUG`, so in a Release build this constant
      // does not exist and this branch does not compile at all; the
      // generated file contributes nothing to a Release binary.
      //
      // No silent fallback: without a pinned value, we deliberately never
      // call `AppCheck.appCheck().token(...)` below. Left unguarded, iOS's
      // own `GACAppCheckDebugProvider` would silently generate and cache a
      // fresh random UUID instead — the exact non-determinism this
      // mechanism exists to eliminate, and the reason recadastro was
      // recurring before this fix. Rejecting immediately, with a
      // greppable code, is deliberately not a native crash: it fails only
      // the specific operation that needs App Check, leaving the rest of
      // the Development Build usable for unrelated work.
      guard let pinnedToken = ajfitPinnedAppCheckDebugToken, !pinnedToken.isEmpty else {
        promise.reject(
          "ERR_APP_CHECK_DEBUG_TOKEN_MISSING",
          "AJFIT_APP_CHECK_DEBUG_TOKEN não está configurado para este Development Build. Defina-o " +
          "no seu .env local (veja .env.example), rode `npx expo prebuild --platform ios` para " +
          "regenerar o projeto nativo, e reconstrua antes de continuar."
        )
        return
      }

      let pinnedTokenPresent = !pinnedToken.isEmpty
      let environmentTokenPresent = ProcessInfo.processInfo.environment["AppCheckDebugToken"] != nil
      let firebaseAppConfigured = FirebaseApp.app() != nil
      let tokenAutoRefreshEnabled = AppCheck.appCheck().isTokenAutoRefreshEnabled
      NSLog(
        "[AJFitAppCheck] fetch configuration " +
        "pinnedTokenPresent=\(pinnedTokenPresent) " +
        "environmentAppCheckDebugTokenPresent=\(environmentTokenPresent) " +
        "firebaseAppConfigured=\(firebaseAppConfigured) " +
        "providerFactory=AppCheckDebugProviderFactory " +
        "providerFactoryInstalledByAJFit=\(AJFitAppCheckConfigurator.debugProviderFactoryInstalledByAJFit) " +
        "tokenAutoRefreshEnabled=\(tokenAutoRefreshEnabled) " +
        "forceRefresh=\(forceRefresh)"
      )
      #endif

      AppCheck.appCheck().token(forcingRefresh: forceRefresh) { result, error in
        if let error {
          // Previously this discarded `error` entirely and always reported the
          // same generic "Firebase App Check token request failed." — making
          // every real failure (debug token rejected by the server, network
          // unreachable, App Attest unavailable, keychain error, etc.)
          // indistinguishable from the JS side. Propagate the real
          // NSError code/domain/description instead so the failure category
          // is visible in the app's own logs, not just Xcode's console.
          let nsError = error as NSError
          #if DEBUG
          let userInfoKeys = nsError.userInfo.keys
            .map { String(describing: $0) }
            .sorted()
          NSLog(
            "[AJFitAppCheck] token fetch error " +
            "domain=\(nsError.domain) " +
            "code=\(nsError.code) " +
            "localizedDescription=\(nsError.localizedDescription) " +
            "userInfoKeys=\(userInfoKeys)"
          )
          #endif
          promise.reject(
            "ERR_APP_CHECK_TOKEN",
            "Firebase App Check token request failed: [\(nsError.domain)#\(nsError.code)] \(nsError.localizedDescription)"
          )
          return
        }

        guard let result else {
          promise.reject(
            "ERR_APP_CHECK_TOKEN",
            "Firebase App Check returned no token and no error (unexpected SDK contract violation)."
          )
          return
        }

        promise.resolve([
          "token": result.token,
          "expireTimeMillis": result.expirationDate.timeIntervalSince1970 * 1000,
        ])
      }
    }
  }
}
