const { createRunOncePlugin, withDangerousMod } = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

// Carries a developer-local, gitignored App Check debug token from `.env`
// into the generated iOS project at `expo prebuild` time — and nowhere
// else. AJFIT_APP_CHECK_DEBUG_TOKEN is read in exactly one place: here.
//
// Deliberately NOT an Info.plist key: Debug and Release share the exact
// same physical Info.plist file for the AJFit target (INFOPLIST_FILE =
// AJFit/Info.plist in both XCBuildConfiguration blocks in
// ios/AJFit.xcodeproj/project.pbxproj) — a value written there would be
// physically present in a Release/TestFlight/App Store bundle even though
// Release code never reads it. Info.plist is a per-TARGET bundle resource,
// not a per-CONFIGURATION one, so nothing written into it can ever be made
// configuration-specific.
//
// Deliberately written into modules/ajfit-app-check/ios/, NOT ios/AJFit/:
// `AJFitAppCheckModule.swift` (which needs to reference the generated
// constant) compiles inside the separate `AJFitAppCheck` CocoaPods pod
// target — not the main `AJFit` app target — so the file has to live where
// that pod's own podspec already globs it up automatically
// (`AJFitAppCheck.podspec`: `s.source_files = '**/*.{h,m,swift}'`, source
// root `modules/ajfit-app-check/ios/`). No Xcode project/pbxproj editing
// needed — `pod install` discovers it on its own the same way it discovers
// every other file in that pod.
//
// modules/ is a normally-committed directory (unlike ios/, which is
// entirely gitignored), so this generated file is individually gitignored
// by exact path — see .gitignore.
//
// Source code is configuration-specific: `#if DEBUG` is a compiler
// preprocessing condition (SWIFT_ACTIVE_COMPILATION_CONDITIONS = DEBUG,
// present only in the project's Debug XCBuildConfiguration). Wrapping the
// ENTIRE generated file — including the string literal itself — in
// `#if DEBUG ... #endif` means the Swift compiler deletes this file's
// content before compiling a Release build. The value never becomes part
// of the Release binary's strings table, because it was never compiled
// into the Release translation unit at all.
const ENV_VAR_NAME = 'AJFIT_APP_CHECK_DEBUG_TOKEN';
const GENERATED_FILE_NAME = 'AJFitAppCheckDebugTokenLocal.swift';
const POD_SOURCE_DIR = path.join('modules', 'ajfit-app-check', 'ios');
const GENERATED_FILE_HEADER =
  '// GENERATED by plugins/app-check-debug-token at `expo prebuild` time. Do not edit or commit.\n' +
  '// Regenerated from the local, gitignored AJFIT_APP_CHECK_DEBUG_TOKEN env var on every prebuild.\n' +
  '// Wrapped in #if DEBUG for its ENTIRE content on purpose: a Release build never compiles this\n' +
  '// file\'s content at all, so the value below can never end up in a Release binary/bundle.\n' +
  '#if DEBUG\n';
const GENERATED_FILE_FOOTER = '#endif\n';

/**
 * Pure so it can be unit-tested without invoking config-plugins/Expo at all.
 * Trims whitespace and treats an empty/missing value as "not configured".
 */
function resolveLocalDebugToken(env) {
  const value = env ? env[ENV_VAR_NAME] : undefined;
  const trimmed = typeof value === 'string' ? value.trim() : '';
  return trimmed.length > 0 ? trimmed : undefined;
}

/**
 * Escapes the value for embedding in a Swift string literal. The token is
 * an opaque UUID-shaped string by convention, but this makes no assumption
 * about its shape.
 */
function swiftStringLiteral(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/**
 * Pure — given a resolved token (or undefined), returns the exact Swift
 * source text to write. `nil` when unset, never an empty string or a
 * fabricated placeholder — the native side treats `nil` as "fail loudly",
 * never as "silently proceed with something".
 */
function generatedSwiftSource(token) {
  const value = token ? swiftStringLiteral(token) : 'nil';
  return (
    GENERATED_FILE_HEADER +
    `let ajfitPinnedAppCheckDebugToken: String? = ${value}\n` +
    GENERATED_FILE_FOOTER
  );
}

function writeGeneratedFile(projectRoot) {
  const targetPath = path.join(projectRoot, POD_SOURCE_DIR, GENERATED_FILE_NAME);
  const source = generatedSwiftSource(resolveLocalDebugToken(process.env));
  fs.writeFileSync(targetPath, source, 'utf8');
}

function withAppCheckDebugToken(config) {
  return withDangerousMod(config, [
    'ios',
    async (dangerousConfig) => {
      writeGeneratedFile(dangerousConfig.modRequest.projectRoot);
      return dangerousConfig;
    },
  ]);
}

module.exports = createRunOncePlugin(
  withAppCheckDebugToken,
  'ajfit-app-check-debug-token',
  '3.0.0',
);
module.exports.ENV_VAR_NAME = ENV_VAR_NAME;
module.exports.GENERATED_FILE_NAME = GENERATED_FILE_NAME;
module.exports.POD_SOURCE_DIR = POD_SOURCE_DIR;
module.exports.resolveLocalDebugToken = resolveLocalDebugToken;
module.exports.generatedSwiftSource = generatedSwiftSource;
