#!/usr/bin/env -S node --import tsx
/**
 * Forces a Workout Lifecycle V2 LEVEL_PROMOTION (BEGINNER -> INTERMEDIATE or
 * INTERMEDIATE -> ADVANCED) for one account, bypassing the normal
 * earned-adherence gate (`authorizeWorkoutLifecycleMutation` EARN check).
 *
 * This exists because the real promotion pipeline
 * (`src/services/workoutLifecycleApplication.ts` prepare/activate +
 * `src/services/prescriptionEvolution.ts#evolvePrescription`) is reachable
 * ONLY through App-Check-enforced Cloud Functions callables with no admin
 * bypass (see functions/src/index.ts — every workoutLifecycle callable sets
 * `enforceAppCheck: true`), so it cannot be driven from a script. Instead
 * this re-derives the exact same prescription content via the pure
 * generation engine (`src/workoutPrescription/engine.ts`) with the same
 * `buildLevelPromotionAnswers` transform `evolvePrescription` uses for
 * LEVEL_PROMOTION (pins frequency/training days from the CURRENT active
 * program — never raw questionnaire availability), then writes the exact
 * same multi-document shape `saveAndActivateWorkoutProgram`'s
 * `evolution_activation` + `nextCycle` branch and `activatePendingEvolution`
 * write via the Admin SDK (which bypasses Firestore Rules, since no grant
 * can be obtained without the App Check callable).
 *
 * NOTE: `evolvePrescription`'s LEVEL_PROMOTION branch always re-templates
 * against the `workoutTemplates` Firestore collection (template library
 * "2.0.0" / selection engine "2.0.0"), even for an account whose current
 * content was generated by the newer "v1.27" local engine. That is existing
 * production behavior (not something this script introduces) — ANY real
 * earned level promotion today produces the same template-lineage change.
 *
 * SAFETY
 * ------
 * This repo has exactly ONE Firebase project configured (`.firebaserc`:
 * "production"). Default mode is DRY RUN — it computes and prints the new
 * prescription/lifecycle documents without writing. Real writes require
 * `--confirm`.
 *
 * CREDENTIALS
 * -----------
 * Application Default Credentials (`gcloud auth application-default login`)
 * with Firestore write access on the target project.
 *
 * USAGE
 * -----
 *   npx tsx scripts/promoteWorkoutLevel.ts <uid> [--target=INTERMEDIATE|ADVANCED] [--confirm]
 */
import { applicationDefault, getApps, initializeApp } from 'firebase-admin/app';
import { FieldValue, getFirestore, type Firestore } from 'firebase-admin/firestore';
import * as crypto from 'crypto';

import { selectTemplate } from '../src/workoutPrescription/selection';
import { generateWorkoutPrescription } from '../src/workoutPrescription/engine';
import { fromWorkoutTemplateDocument, WORKOUT_TEMPLATE_DOCUMENT_VERSION } from '../src/workoutPrescription/templateDocument';
import { PRESCRIPTION_VERSIONS, type QuestionnaireAnswers, type FinalWorkoutPlan, type CanonicalTemplate } from '../src/workoutPrescription/types';
import { EXERCISES_SEED } from '../src/data/exercisesSeedData';
import { exerciseCatalogErrors } from '../src/services/exerciseCatalogValidity';
import { canonicalizeLimitationProfiles, LIMITATION_DATASET_STATE_COLLECTION, LIMITATION_DATASET_ACTIVE_DOCUMENT, type LimitationDatasetSnapshot } from '../src/workoutPrescription/limitationDataset';
import type { LimitationCatalogExercise } from '../src/workoutPrescription/limitationResolver';
import { buildLevelPromotionAnswers, type LevelPromotionTarget } from '../src/prescriptionEvolution/levelPromotion';
import {
  buildPrescriptionInputSnapshot,
  questionnaireAnswersFromPrescriptionInputs,
  questionnaireLevelForCurrentLevel,
} from '../src/workoutLifecycle/prescriptionInputs';
import {
  cycleIdForOperation,
  programInstanceIdForOperation,
  lifecycleEventId,
  lifecycleStableHash,
} from '../src/workoutLifecycle/domain';
import type { CurrentTrainingLevel, PrescriptionInputSnapshot } from '../src/workoutLifecycle/types';

const projectId = 'ajfit-2f321';
if (getApps().length === 0) initializeApp({ credential: applicationDefault(), projectId });
const db: Firestore = getFirestore();

const PROMOTION_PATH: Record<CurrentTrainingLevel, LevelPromotionTarget | null> = {
  BEGINNER: 'INTERMEDIATE',
  INTERMEDIATE: 'ADVANCED',
  ADVANCED: null,
};

function parseArgs(argv: string[]) {
  const positional = argv.filter((a) => !a.startsWith('--'));
  const confirm = argv.includes('--confirm');
  const targetArg = argv.find((a) => a.startsWith('--target='))?.split('=')[1];
  const [uid] = positional;
  return { uid, confirm, targetArg };
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function withoutUndefined<T>(value: T): T {
  if (Array.isArray(value)) return value.map(withoutUndefined) as T;
  if (isPlainObject(value)) {
    return Object.fromEntries(
      Object.entries(value).filter(([, v]) => v !== undefined).map(([k, v]) => [k, withoutUndefined(v)]),
    ) as T;
  }
  return value;
}

function canonicalStringify(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalStringify).join(',')}]`;
  if (isPlainObject(value)) {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalStringify(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

/** Mirrors `contentIdentityFor` in src/services/workoutPrograms.ts exactly (same preimage shape/hash). */
function contentIdentityFor(input: {
  questionnaireId: string;
  questionnaireVersion: number;
  plan: FinalWorkoutPlan;
  template: Pick<CanonicalTemplate, never> & { id: string; version: number; contentHash: string };
}): string {
  const preimage = canonicalStringify({
    questionnaireId: input.questionnaireId,
    questionnaireVersion: input.questionnaireVersion,
    prescriptionId: input.plan.planId,
    templateId: input.template.id,
    templateVersion: input.template.version,
    templateContentHash: input.template.contentHash,
    versions: input.plan.versions,
    limitationDatasetVersion: input.plan.limitationDatasetVersion,
    limitationDatasetHash: input.plan.limitationDatasetHash,
    adaptationStage: input.plan.adaptationStage ?? null,
  });
  return `wpg_${lifecycleStableHash(preimage)}`;
}

async function loadLimitationDataset(needsExercises: boolean): Promise<LimitationDatasetSnapshot> {
  const identitySnap = await db.doc(`${LIMITATION_DATASET_STATE_COLLECTION}/${LIMITATION_DATASET_ACTIVE_DOCUMENT}`).get();
  if (!identitySnap.exists) throw new Error('LIMITATION_DATASET_ACTIVE_IDENTITY_MISSING');
  const identityData = identitySnap.data()!;
  const version = identityData.datasetVersion as string;
  const hash = identityData.limitationDatasetHash as string;
  if (typeof version !== 'string' || typeof hash !== 'string' || !/^[a-f0-9]{64}$/.test(hash)) {
    throw new Error('LIMITATION_DATASET_ACTIVE_IDENTITY_INVALID');
  }
  if (!needsExercises) return { version, hash, source: 'firestore', exercises: [] };

  const snap = await db.collection('exercises').get();
  const documents = snap.docs.map((d) => ({ id: d.id, data: { ...d.data(), id: d.id } }));
  const errors = exerciseCatalogErrors(documents);
  if (errors.length) throw new Error(errors.join(','));
  const exercises = documents.map((d) => d.data as LimitationCatalogExercise);
  const profiles = exercises
    .filter((e) => (e as any).limitationProfile != null)
    .map((e: any) => ({ exerciseId: e.id, limitationProfile: e.limitationProfile }));
  const computedHash = crypto.createHash('sha256')
    .update(canonicalizeLimitationProfiles(profiles, exercises as any))
    .digest('hex');
  if (computedHash !== hash) throw new Error('LIMITATION_DATASET_VERSION_MISMATCH');
  return { version, hash, source: 'firestore', exercises };
}

async function main() {
  const { uid, confirm, targetArg } = parseArgs(process.argv.slice(2));
  if (!uid) {
    console.error('Usage: promoteWorkoutLevel.ts <uid> [--target=INTERMEDIATE|ADVANCED] [--confirm]');
    process.exitCode = 1;
    return;
  }

  console.log(`Project: ${projectId}`);
  console.log(`UID: ${uid}`);

  const lifecycleRef = db.doc(`users/${uid}/workoutLifecycleState/current`);
  const lifecycleSnap = await lifecycleRef.get();
  if (!lifecycleSnap.exists) {
    console.error('Aborting: users/{uid}/workoutLifecycleState/current not found — no V2 lifecycle for this account.');
    process.exitCode = 1;
    return;
  }
  const lifecycle = lifecycleSnap.data()!;
  const currentLevel = lifecycle.currentTrainingLevel as CurrentTrainingLevel;
  const autoTarget = PROMOTION_PATH[currentLevel];
  const targetLevel = (targetArg as LevelPromotionTarget | undefined) ?? autoTarget ?? undefined;
  if (!targetLevel || PROMOTION_PATH[currentLevel] !== targetLevel) {
    console.error(
      `Aborting: invalid promotion ${currentLevel} -> ${targetLevel ?? '(none)'}. `
      + `Allowed: ${currentLevel === 'ADVANCED' ? 'none (already ADVANCED)' : `${currentLevel} -> ${autoTarget}`}.`,
    );
    process.exitCode = 1;
    return;
  }
  console.log(`Promotion: ${currentLevel} -> ${targetLevel}`);

  const oldInstanceId = lifecycle.activeProgramInstanceId as string;
  const oldCycleId = lifecycle.currentCycleId as string;
  const oldContentIdentity = lifecycle.activeContentIdentity as string;

  const [instanceSnap, cycleSnap, programSnap] = await Promise.all([
    db.doc(`users/${uid}/programInstances/${oldInstanceId}`).get(),
    db.doc(`users/${uid}/trainingCycles/${oldCycleId}`).get(),
    db.doc(`users/${uid}/workoutPrograms/${oldContentIdentity}`).get(),
  ]);
  if (!instanceSnap.exists || !cycleSnap.exists || !programSnap.exists) {
    console.error('Aborting: active programInstance/trainingCycle/workoutProgram not found for this uid.');
    process.exitCode = 1;
    return;
  }
  const instance = instanceSnap.data()!;
  const program = programSnap.data()! as FinalWorkoutPlan & Record<string, unknown>;

  // ─── Authoritative current inputs (mirrors loadAuthoritativePrescriptionInputs) ───
  let currentAnswers: QuestionnaireAnswers;
  const persistedSnapshot = instance.prescriptionInputSnapshot as PrescriptionInputSnapshot | undefined;
  if (persistedSnapshot) {
    currentAnswers = questionnaireAnswersFromPrescriptionInputs(persistedSnapshot.inputs) as QuestionnaireAnswers;
    currentAnswers.level = questionnaireLevelForCurrentLevel(currentLevel);
  } else {
    const questionnaireSnap = await db.doc(`users/${uid}/questionnaires/${instance.questionnaireId}`).get();
    if (!questionnaireSnap.exists) {
      console.error('Aborting: source questionnaire not found and no prescriptionInputSnapshot on the active instance.');
      process.exitCode = 1;
      return;
    }
    currentAnswers = (questionnaireSnap.data()!.answers) as QuestionnaireAnswers;
  }

  // ─── Pin frequency/training days from the CURRENT active program (never raw questionnaire availability) ───
  const pinnedFrequency = (program.prescribedTrainingFrequency as number | undefined) ?? (program.prescribedStructuredDays as number);
  const scheduleMode = (program.scheduleMode as string | undefined) ?? 'fixed';
  const pinnedTrainingDays = scheduleMode === 'fixed'
    ? ((program.weeklySchedule as any[] | undefined) ?? []).filter((d) => d.state === 'TRAINING').map((d) => d.weekday)
    : [];

  const syntheticAnswers = buildLevelPromotionAnswers({
    currentAnswers,
    targetLevel,
    pinnedFrequency,
    pinnedTrainingDays,
    scheduleMode: scheduleMode as 'fixed' | 'flexible',
  });

  // ─── Template selection + load (always the "v2" workoutTemplates collection — see header note) ───
  const selection = selectTemplate(syntheticAnswers);
  if (selection.status !== 'SELECTED') {
    console.error('Aborting: MISSING_TEMPLATE', selection.reasonCodes);
    process.exitCode = 1;
    return;
  }
  const templateSnap = await db.doc(`workoutTemplates/${selection.decision.templateId}`).get();
  if (!templateSnap.exists) {
    console.error(`Aborting: workoutTemplates/${selection.decision.templateId} not found.`);
    process.exitCode = 1;
    return;
  }
  const templateDoc = templateSnap.data()! as any;
  if (
    templateDoc.status !== 'active'
    || templateDoc.version !== WORKOUT_TEMPLATE_DOCUMENT_VERSION
    || templateDoc.sourceVersion !== PRESCRIPTION_VERSIONS.templateLibrary
    || typeof templateDoc.contentHash !== 'string'
    || !/^[a-f0-9]{64}$/.test(templateDoc.contentHash)
    || !Array.isArray(templateDoc.sessions) || templateDoc.sessions.length === 0
  ) {
    console.error(`Aborting: workoutTemplates/${selection.decision.templateId} failed shape/version validation.`);
    process.exitCode = 1;
    return;
  }
  const template = fromWorkoutTemplateDocument(templateDoc);

  // ─── Limitation dataset (identity always required; exercises only if declared) ───
  const needsLimitationCatalog = syntheticAnswers.specialConditions.includes('musculoskeletal_limitation');
  const limitationDataset = await loadLimitationDataset(needsLimitationCatalog);

  // ─── Generate the new prescription content ───
  const result = generateWorkoutPrescription(syntheticAnswers, {
    template,
    exerciseCatalog: needsLimitationCatalog ? limitationDataset.exercises : undefined,
    limitationDataset,
  });
  if (result.status !== 'SUCCESS') {
    console.error(`Aborting: prescription generation failed (${result.status})`, (result as any).reasonCodes);
    process.exitCode = 1;
    return;
  }
  const plan = result.plan;

  const resultFrequency = plan.prescribedTrainingFrequency ?? plan.prescribedStructuredDays;
  if (resultFrequency !== pinnedFrequency) {
    console.error(`Aborting: FREQUENCY_NOT_PRESERVED (pinned ${pinnedFrequency}, got ${resultFrequency}).`);
    process.exitCode = 1;
    return;
  }

  const knownExerciseIds = new Set(EXERCISES_SEED.map((e) => e.id));
  const missingExercises = [...new Set(plan.sessions.flatMap((s) => s.exercises.map((e) => e.exerciseId)))]
    .filter((id) => !knownExerciseIds.has(id));
  if (missingExercises.length) {
    console.error('Aborting: MISSING_EXERCISE', missingExercises);
    process.exitCode = 1;
    return;
  }

  const prescriptionInputSnapshot = buildPrescriptionInputSnapshot({
    answers: syntheticAnswers,
    currentTrainingLevel: targetLevel,
    source: 'LEVEL_PROMOTION',
  });

  const contentIdentity = contentIdentityFor({
    questionnaireId: instance.questionnaireId,
    questionnaireVersion: program.questionnaireVersion as number,
    plan,
    template: { id: templateDoc.id, version: templateDoc.version, contentHash: templateDoc.contentHash },
  });
  const prescriptionIdentity = plan.planId;

  const operationKey = `activation:evolution:${oldInstanceId}:LEVEL_PROMOTION`;
  const newInstanceId = programInstanceIdForOperation(operationKey);
  const newCycleId = cycleIdForOperation(`cycle:${operationKey}`);
  const eventId = lifecycleEventId('LEVEL_PROMOTED', operationKey);

  console.log('\n--- Plan ---');
  console.log('old programInstance:', oldInstanceId, '-> new:', newInstanceId);
  console.log('old trainingCycle:', oldCycleId, '-> new:', newCycleId);
  console.log('old contentIdentity:', oldContentIdentity, '-> new:', contentIdentity);
  console.log('new prescriptionIdentity:', prescriptionIdentity);
  console.log('template:', templateDoc.id, 'v' + templateDoc.version, templateDoc.sourceVersion);
  console.log('preserved frequency:', resultFrequency, 'days, sessions:', plan.sessions.length);
  console.log('lifecycleEvent:', eventId);

  if (!confirm) {
    console.log('\nDry run only — no write performed. Re-run with --confirm to write.');
    return;
  }

  await db.runTransaction(async (tx) => {
    const [freshLifecycleSnap, freshInstanceSnap, freshCycleSnap, freshProgramSnap, newProgramSnap, pendingSnap] = await Promise.all([
      tx.get(lifecycleRef),
      tx.get(db.doc(`users/${uid}/programInstances/${oldInstanceId}`)),
      tx.get(db.doc(`users/${uid}/trainingCycles/${oldCycleId}`)),
      tx.get(db.doc(`users/${uid}/workoutPrograms/${oldContentIdentity}`)),
      tx.get(db.doc(`users/${uid}/workoutPrograms/${contentIdentity}`)),
      tx.get(db.doc(`users/${uid}/pendingEvolutions/current`)),
    ]);
    const freshLifecycle = freshLifecycleSnap.data();
    if (
      !freshLifecycle
      || freshLifecycle.currentTrainingLevel !== currentLevel
      || freshLifecycle.activeProgramInstanceId !== oldInstanceId
      || freshLifecycle.activeContentIdentity !== oldContentIdentity
      || !freshInstanceSnap.exists
      || !freshCycleSnap.exists
      || !freshProgramSnap.exists
    ) {
      throw new Error('WORKOUT_LIFECYCLE_STALE_STATE — account changed since dry run; re-run the script.');
    }

    const now = FieldValue.serverTimestamp();

    tx.update(freshInstanceSnap.ref, { supersededAt: now, updatedAt: now });
    tx.update(freshCycleSnap.ref, { status: 'COMPLETED', completedAt: now, completionReason: 'EARNED_EVOLUTION', updatedAt: now });
    tx.update(freshProgramSnap.ref, { status: 'superseded', updatedAt: now });

    if (!newProgramSnap.exists) {
      tx.set(db.doc(`users/${uid}/workoutPrograms/${contentIdentity}`), withoutUndefined({
        ...plan,
        programId: contentIdentity,
        prescriptionId: plan.planId,
        status: 'active',
        source: 'evolution_activation',
        templateVersion: templateDoc.version,
        templateSourceVersion: templateDoc.sourceVersion,
        templateContentHash: templateDoc.contentHash,
        questionnaireId: instance.questionnaireId,
        questionnaireVersion: program.questionnaireVersion,
        createdAt: now,
        activatedAt: now,
        updatedAt: now,
      }));
    }

    tx.set(db.doc(`users/${uid}/programInstances/${newInstanceId}`), {
      programInstanceId: newInstanceId,
      cycleId: newCycleId,
      contentIdentity,
      prescriptionIdentity,
      questionnaireId: instance.questionnaireId,
      prescriptionInputSnapshot,
      activatedAt: now,
      supersededAt: null,
      previousProgramInstanceId: oldInstanceId,
      activationReason: 'EVOLUTION_ACTIVATION',
      schemaVersion: 2,
      createdAt: now,
      updatedAt: now,
    });

    tx.set(db.doc(`users/${uid}/trainingCycles/${newCycleId}`), {
      cycleId: newCycleId,
      level: targetLevel,
      cycleNumber: 1,
      status: 'ACTIVE',
      origin: 'V2_NATIVE',
      programInstanceId: newInstanceId,
      previousProgramInstanceId: oldInstanceId,
      startedAt: now,
      eligibleAt: null,
      completedAt: null,
      completionReason: null,
      progressionReason: 'EARNED_LEVEL_PROMOTION',
      schemaVersion: 2,
      createdAt: now,
      updatedAt: now,
    });

    tx.update(lifecycleRef, {
      currentTrainingLevel: targetLevel,
      currentCycleId: newCycleId,
      currentCycleNumber: 1,
      activeProgramInstanceId: newInstanceId,
      activeContentIdentity: contentIdentity,
      activePrescriptionIdentity: prescriptionIdentity,
      updatedAt: now,
    });

    tx.set(db.doc(`users/${uid}/workoutLifecycleEvents/${eventId}`), {
      eventId,
      type: 'LEVEL_PROMOTED',
      occurredAt: now,
      cycleId: newCycleId,
      programInstanceId: newInstanceId,
      idempotencyKey: operationKey,
      payload: { fromLevel: currentLevel, toLevel: targetLevel, triggeredBy: 'admin_script' },
      schemaVersion: 2,
    });

    if (pendingSnap.exists) tx.delete(pendingSnap.ref);
  });

  console.log(`\nDone. ${uid} promoted ${currentLevel} -> ${targetLevel}. New active content: ${contentIdentity}.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
