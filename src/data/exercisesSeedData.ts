/**
 * Derives `substitution.similarExerciseIds` from `substitutionGroup`
 * membership instead of hand-curated pairwise lists (docs/27 §10): two
 * exercises in the same group already share primary muscle, movement
 * pattern and mechanic by construction (each group is a single family —
 * e.g. `hip_hinge`, `horizontal_back_row`), so grouping IS the
 * biomechanical-similarity signal, not a same-muscle-only shortcut.
 *
 * Within a group, same-`laterality` peers are preferred and listed first
 * (closer substitution), then cross-laterality peers fill the remainder,
 * capped at 4 total. A lone member of a group gets `[]` — no forced match.
 */
function buildSubstitutions(entries: SeedEntry[]): ExerciseSeedInput[] {
  const byGroup = new Map<string, SeedEntry[]>();
  for (const e of entries) {
    if (!e.substitutionGroup) continue;
    const list = byGroup.get(e.substitutionGroup) ?? [];
    list.push(e);
    byGroup.set(e.substitutionGroup, list);
  }

  return entries.map(({ substitutionGroup, ...rest }) => {
    if (!substitutionGroup) {
      return {
        ...rest,
        substitution: {
          similarExerciseIds: [],
        },
      };
    }
    const peers = (byGroup.get(substitutionGroup) ?? []).filter((p) => p.id !== rest.id);
    const sameLaterality = peers.filter((p) => p.movement.laterality === rest.movement.laterality);
    const crossLaterality = peers.filter((p) => p.movement.laterality !== rest.movement.laterality);
    const similarExerciseIds = [...sameLaterality, ...crossLaterality].slice(0, 4).map((p) => p.id);
    return {
      ...rest,
      substitution: {
        group: substitutionGroup,
        similarExerciseIds,
      },
    };
  });
}

export const EXERCISES_SEED: ExerciseSeedInput[] = buildSubstitutions(RAW_EXERCISES);

/** All `MuscleId`s actually used by the seed dataset — sanity-check helper for tests/docs. */
export function usedMuscleIds(): MuscleId[] {
  const set = new Set<MuscleId>();
  for (const e of EXERCISES_SEED) {
    set.add(e.target.primaryMuscle);
    e.target.secondaryMuscles.forEach((m) => set.add(m));
  }
  return Array.from(set).sort();
}
