import {
  AESEncryptionKey,
  AESKeySize,
  AESSealedData,
  aesDecryptAsync,
  aesEncryptAsync,
} from 'expo-crypto';

import { PhotoVaultError } from './photoVaultErrors';
import { base64ByteLength } from './photoVaultKeyStorage';

/**
 * AES-256-GCM engine for the Photo Vault.
 *
 * Pure crypto and binary framing — no Firebase, no Storage, no filesystem, no
 * SecureStore, no UI. The file pipeline lives in
 * `services/photoVaultFileCrypto.ts` and is the only caller.
 *
 * Uses `expo-crypto`'s native AES-GCM. No algorithm is implemented by hand.
 */

// ── Envelope format ────────────────────────────────────────────────────────
//
// Compact binary, not JSON+base64: a 10 MB photo would grow ~33% and would
// have to exist as a giant string in memory.
//
//   offset  size  field
//   ------  ----  --------------------------------------------------
//        0     4  MAGIC "AJFV"        (identifies the format; not a secret)
//        4     1  VERSION             (1)
//        5     1  IV length           (12)
//        6     1  TAG length          (16)
//        7     1  reserved            (0, keeps the header 8-byte aligned)
//        8    12  IV / nonce
//       20    16  GCM authentication tag
//       36     N  ciphertext (tag NOT appended)
//
// Every header field is either checked by the strict parser below or covered
// by GCM authentication, so a tampered file always fails — see the AAD note.

/** "AJFV" — AJ Fit Vault. */
const MAGIC = Uint8Array.from([0x41, 0x4a, 0x46, 0x56]);

export const ENCRYPTION_VERSION = 1;
export const ENCRYPTION_ALGORITHM = 'AES-256-GCM';

/** 96-bit nonce: the size AES-GCM is specified for, and expo-crypto's default. */
export const IV_BYTES = 12;

/** 128-bit tag: expo-crypto's default and the only value Apple accepts. */
export const TAG_BYTES = 16;

const MAGIC_OFFSET = 0;
const VERSION_OFFSET = 4;
const IV_LENGTH_OFFSET = 5;
const TAG_LENGTH_OFFSET = 6;
const IV_OFFSET = 8;
const TAG_OFFSET = IV_OFFSET + IV_BYTES;
export const HEADER_BYTES = TAG_OFFSET + TAG_BYTES;

const VAULT_KEY_BYTES = 32;

export interface EncryptedEnvelope {
  /** The complete `.enc` file contents. */
  bytes: Uint8Array;
  /** Base64 IV, for the Firestore metadata defined in phase 4. */
  iv: string;
}

/**
 * Imports the vault key for a single operation.
 *
 * The base64 length is re-validated here even though the storage layer
 * already did: this module must not inherit another layer's assumption about
 * key size (defense in depth). The raw key bytes are never materialized as a
 * JavaScript array — `import` decodes inside the native module, so there is
 * no plaintext key buffer for us to leak or fail to zero.
 */
async function importVaultKey(vaultKeyBase64: string): Promise<AESEncryptionKey> {
  if (
    typeof vaultKeyBase64 !== 'string' ||
    base64ByteLength(vaultKeyBase64) !== VAULT_KEY_BYTES
  ) {
    throw new PhotoVaultError('vaultCryptoInvalidKey');
  }

  let key: AESEncryptionKey;
  try {
    key = await AESEncryptionKey.import(vaultKeyBase64, 'base64');
  } catch {
    throw new PhotoVaultError('vaultCryptoInvalidKey');
  }

  // Second, independent check: the module's own view of the imported key.
  if (key.size !== AESKeySize.AES256) {
    throw new PhotoVaultError('vaultCryptoInvalidKey');
  }

  return key;
}

function toBase64(bytes: Uint8Array): string {
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return globalThis.btoa(binary);
}

/**
 * Encrypts photo bytes into a versioned envelope.
 *
 * A fresh nonce is generated by expo-crypto for every call (its default
 * `{ length: 12 }` behaviour), so the same photo encrypted twice yields
 * different ciphertext and the key/nonce pair is never reused.
 */
export async function encryptBytes(
  plaintext: Uint8Array,
  vaultKeyBase64: string,
): Promise<EncryptedEnvelope> {
  const key = await importVaultKey(vaultKeyBase64);

  let iv: Uint8Array;
  let tag: Uint8Array;
  let ciphertext: Uint8Array;
  try {
    const sealed = await aesEncryptAsync(plaintext, key);

    // Read back as raw byte parts. The project already found that
    // `combined()` / `fromCombined()` and the base64 encodings do not
    // round-trip correctly on Android (see lib/secureAuthStorage.ts), so the
    // three parts are always handled as bytes and framed by hand below.
    iv = await sealed.iv('bytes');
    tag = await sealed.tag('bytes');
    ciphertext = await sealed.ciphertext({ includeTag: false, encoding: 'bytes' });
  } catch {
    throw new PhotoVaultError('vaultCryptoEncryptFailed');
  }

  if (iv.length !== IV_BYTES || tag.length !== TAG_BYTES) {
    // The envelope layout is fixed for version 1; a different shape means we
    // would write a file our own parser could not read.
    throw new PhotoVaultError('vaultCryptoEncryptFailed');
  }

  const bytes = new Uint8Array(HEADER_BYTES + ciphertext.length);
  bytes.set(MAGIC, MAGIC_OFFSET);
  bytes[VERSION_OFFSET] = ENCRYPTION_VERSION;
  bytes[IV_LENGTH_OFFSET] = IV_BYTES;
  bytes[TAG_LENGTH_OFFSET] = TAG_BYTES;
  bytes.set(iv, IV_OFFSET);
  bytes.set(tag, TAG_OFFSET);
  bytes.set(ciphertext, HEADER_BYTES);

  return { bytes, iv: toBase64(iv) };
}

interface ParsedEnvelope {
  iv: Uint8Array;
  tag: Uint8Array;
  ciphertext: Uint8Array;
}

/**
 * Strictly parses an envelope. Fails closed on anything unexpected — a file
 * we cannot fully account for is never partially trusted.
 *
 * Exported so the format can be tested independently of the cipher.
 */
export function parseEnvelope(bytes: Uint8Array): ParsedEnvelope {
  if (!(bytes instanceof Uint8Array) || bytes.length < HEADER_BYTES) {
    throw new PhotoVaultError('vaultCryptoInvalidFile');
  }

  for (let i = 0; i < MAGIC.length; i += 1) {
    if (bytes[MAGIC_OFFSET + i] !== MAGIC[i]) {
      throw new PhotoVaultError('vaultCryptoInvalidFile');
    }
  }

  // Unknown version: never guess how a future format is laid out.
  if (bytes[VERSION_OFFSET] !== ENCRYPTION_VERSION) {
    throw new PhotoVaultError('vaultCryptoUnsupportedVersion');
  }

  if (bytes[IV_LENGTH_OFFSET] !== IV_BYTES || bytes[TAG_LENGTH_OFFSET] !== TAG_BYTES) {
    throw new PhotoVaultError('vaultCryptoInvalidFile');
  }

  // A header with no ciphertext cannot be a photo.
  if (bytes.length === HEADER_BYTES) {
    throw new PhotoVaultError('vaultCryptoInvalidFile');
  }

  return {
    iv: bytes.slice(IV_OFFSET, IV_OFFSET + IV_BYTES),
    tag: bytes.slice(TAG_OFFSET, TAG_OFFSET + TAG_BYTES),
    ciphertext: bytes.slice(HEADER_BYTES),
  };
}

/**
 * Reads the non-secret framing of an envelope without decrypting it.
 *
 * Used to cross-check a downloaded file against the Firestore metadata that
 * claims to describe it, before any key is involved.
 */
export function describeEnvelope(bytes: Uint8Array): { version: number; iv: string } {
  const { iv } = parseEnvelope(bytes);
  return { version: ENCRYPTION_VERSION, iv: toBase64(iv) };
}

/**
 * Decrypts an envelope back to the original photo bytes.
 *
 * GCM verifies the authentication tag: a tampered nonce, tag or ciphertext,
 * or a wrong key, all fail here. Nothing partial is ever returned.
 */
export async function decryptBytes(
  envelope: Uint8Array,
  vaultKeyBase64: string,
): Promise<Uint8Array> {
  const { iv, tag, ciphertext } = parseEnvelope(envelope);
  const key = await importVaultKey(vaultKeyBase64);

  try {
    const sealed = AESSealedData.fromParts(iv, ciphertext, tag);
    const plaintext = await aesDecryptAsync(sealed, key, { output: 'bytes' });
    return plaintext as Uint8Array;
  } catch {
    // Authentication failure and a wrong key are indistinguishable by design;
    // both mean the bytes must not be trusted.
    throw new PhotoVaultError('vaultCryptoIntegrityFailed');
  }
}
