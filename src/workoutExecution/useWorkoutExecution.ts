function deviceTimezone(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
  } catch {
    return 'UTC';
  }
}

/**
 * Surfaced when `start()` fails to acquire the persistent
 * `workoutExecutionState/current` mutex (docs P0) — lets the caller show a
 * targeted recovery UI instead of a generic failure. Never inferred from a
 * generic catch; only set from the two typed errors the service throws.
 */
export type WorkoutExecutionStartError =
  | { code: 'CONFLICT'; active: { executionId: string; sessionIndex: number; scheduledLocalDate: string } }
  | { code: 'LEGACY_PENDING'; executionIds: string[] }
  | { code: 'UNKNOWN' };

export type WorkoutExecutionStartResult =
  | { execution: PersistedWorkoutExecution; error: null }
  | { execution: null; error: WorkoutExecutionStartError };

export interface WorkoutExecutionController {
  execution: PersistedWorkoutExecution | null;
  starting: boolean;
  /** Set only when the most recent `start()` call failed — cleared at the start of every new `start()` call. */
  startError: WorkoutExecutionStartError | null;
  /** A mutation failed and remains queued for the finish-barrier retry. */
  hasUnreconciledMutations: boolean;
  /**
   * Start instant for the session's UI timer, epoch ms. It uses the persisted
   * `serverTimestamp()` once reconciled; until then it uses one `Date.now()`
   * captured at start. The local value is presentation-only, is never a
   * lifecycle authority, and is never regenerated by a remount/foreground.
   */
  workoutStartedAtMs: number | null;
  /**
   * Starts (or resumes, or restarts after abandon) the execution for
   * `sessionIndex` — idempotent (docs §22–25). Read the error straight off
   * this resolved result, not off `startError`, when branching immediately
   * on the outcome — `startError` is React state and lags one render behind
   * this promise's resolution.
   */
  start: (sessionIndex: number, preparation?: {
    manualSubstitutionContext?: ManualSubstitutionUserContext | null;
    manualSubstitutionContextStatus?: 'loading' | 'ready' | 'error';
  }) => Promise<WorkoutExecutionStartResult>;
  /** Starts only the resolver-provided next fixed opportunity when it is exactly tomorrow. */
  startAdvanced: (resolution: ScheduleResolution) => Promise<WorkoutExecutionStartResult>;
  /**
   * Adopts an already-verified `IN_PROGRESS` execution directly into this
   * hook's state — used by Workout Recovery once the bootstrap check
   * (`useWorkoutSessionRecovery`) has loaded and validated it. Never writes
   * to Firestore (the execution and its `current` pointer already exist and
   * are already consistent) and never renews `startedAt` — this is resume,
   * not restart, so the session timer keeps counting from the original
   * instant.
   */
  adoptExecution: (execution: PersistedWorkoutExecution) => void;
  recordSet: (exerciseIndex: number, setIndex: number, weightKg: number | null, actualReps?: number | null) => Promise<void>;
  skipSet: (exerciseIndex: number, setIndex: number) => Promise<void>;
  skipExercise: (exerciseIndex: number) => Promise<void>;
  /**
   * Cardio Finisher Completion Recovery hardening (2026-09): persists the
   * cardio finisher's completion durably on the execution BEFORE the caller
   * advances to `finish()` — see `completeCardioExecution`'s doc comment
   * (`services/workoutExecutions.ts`) for why this is a separate recoverable
   * step rather than folded into `finish()`. Returns a typed result, never
   * throws: a network/transaction failure must never be read as "cardio is
   * confirmed done" by the caller (docs — a false-positive here is exactly
   * the bug this hardening fixes). `{ ok: true }` also covers the idempotent
   * "already completed" case — the caller always proceeds to `finish()`
   * next either way.
   */
  /** Flushes queued set writes, then atomically finalizes cardio (if supplied), Execution and Schedule server-side. */
  finalize: (actualCardioDurationSeconds?: number, mode?: WorkoutFinalizationMode) => Promise<
    { ok: true; result: FinalizeWorkoutSessionResult } | { ok: false; error: unknown }
  >;
  /**
   * Distinct from `finish` — never advances the Schedule Engine (docs §36).
   * Abandons the currently-tracked execution. Returns a typed result instead
   * of throwing/swallowing: the caller (WorkoutScreen's discard flow) must be
   * able to tell success from failure to decide whether it's safe to
   * navigate away — Firestore, not this promise resolving, is the authority
   * on whether the execution actually left IN_PROGRESS.
   */
  abandon: () => Promise<{ ok: true } | { ok: false; error: unknown }>;
  /**
   * Abandons an arbitrary execution by id — used to resolve a `CONFLICT`/
   * `LEGACY_PENDING` `startError` (a pending session this hook isn't
   * currently tracking) before retrying `start()` (docs §11/§12). Clears
   * `startError` on success so the caller can immediately retry.
   */
  abandonExecutionById: (executionId: string) => Promise<void>;
}

/**
 * Bridges the Firestore-backed Execution service (src/services/
 * workoutExecutions.ts) to the active program/session, mirroring
 * `useWorkoutSchedule`'s shape. Owned by `AppShell` — `WorkoutScreen` stays
 * presentation-only and reaches persistence only through the callbacks this
 * hook produces (docs/workout-lifecycle/09_WORKOUT_EXECUTION_AND_HISTORY.md).
 */
export function useWorkoutExecution(program: WorkoutProgramSnapshot | null, timezone: string | undefined): WorkoutExecutionController {
  const { user } = useAuth();
  const uid = user?.uid ?? null;
  const preparationKey = uid && program
    ? `${uid}:${program.programInstanceId ?? program.programId}`
    : null;
  const [execution, setExecution] = useState<PersistedWorkoutExecution | null>(null);
  const [starting, setStarting] = useState(false);
  const [startError, setStartError] = useState<WorkoutExecutionStartError | null>(null);
  const [hasUnreconciledMutations, setHasUnreconciledMutations] = useState(false);
  const startInFlightRef = useRef<WorkoutStartFlight<WorkoutExecutionStartResult> | null>(null);
  const mutationQueueRef = useRef(new WorkoutMutationQueue());
  // Presentation-only start instant for a newly committed execution. It is
  // cleared only when canonical server timestamps arrive (or start fails).
  const pendingStartedAtMsRef = useRef<number | null>(null);
  const startPreparationRef = useRef<{
    key: string;
    latestLegacyIds: string[] | null;
    latestPreferences: PermanentExerciseSubstitutionPreferences | null;
  } | null>(null);

  // Legacy compatibility cannot be removed until the remotely-controlled
  // mutex hardening gate is guaranteed on for all writers. Keep that query —
  // and the permanent-preference collection — warm while Home is visible so
  // the confirm click normally waits only for the authoritative transaction.
  useEffect(() => {
    if (!uid || !preparationKey) {
      startPreparationRef.current = null;
      return undefined;
    }
    const state: NonNullable<typeof startPreparationRef.current> = {
      key: preparationKey,
      latestLegacyIds: null,
      latestPreferences: null,
    };
    startPreparationRef.current = state;
    const unsubscribeLegacy = subscribeToInProgressWorkoutExecutionIds(uid, (ids, metadata) => {
      if (!metadata.fromCache) {
        state.latestLegacyIds = ids;
      }
    });
    const unsubscribePreferences = subscribeToPermanentExerciseSubstitutionPreferences(
      uid,
      (preferences, metadata) => {
        if (!metadata?.fromCache) {
          state.latestPreferences = preferences;
        }
      },
    );
    return () => {
      unsubscribeLegacy();
      unsubscribePreferences();
      if (startPreparationRef.current === state) startPreparationRef.current = null;
    };
  }, [preparationKey, uid]);

  const startWithDates = useCallback((input: {
    sessionIndex: number;
    scheduledLocalDate: string;
    performedLocalDate: string;
    preparation?: {
      manualSubstitutionContext?: ManualSubstitutionUserContext | null;
      manualSubstitutionContextStatus?: 'loading' | 'ready' | 'error';
    };
  }): Promise<WorkoutExecutionStartResult> => {
    const unknownError = { execution: null, error: { code: 'UNKNOWN' as const } };
    if (!uid || !program) {
      if (typeof __DEV__ !== 'undefined' && __DEV__) {
        logInfo('workout_performance', 'start_workout_guard_exit', {
          reason: !uid ? 'AUTH_USER_MISSING' : 'PROGRAM_MISSING',
        });
      }
      return Promise.resolve(unknownError);
    }
    const { sessionIndex, scheduledLocalDate, performedLocalDate, preparation } = input;
    const executionScopeId = program.programInstanceId ?? program.programId;
    const requestKey = `${uid}:${executionScopeId}:${sessionIndex}:${scheduledLocalDate}:${performedLocalDate}`;
    const flight = beginWorkoutStartFlight(startInFlightRef, requestKey, async (): Promise<WorkoutExecutionStartResult> => {
      setStarting(true);
      setStartError(null);
      mutationQueueRef.current.reset();
      setHasUnreconciledMutations(false);
      pendingStartedAtMsRef.current = Date.now();
      const startedAtMs = Date.now();
      try {
        if (typeof __DEV__ !== 'undefined' && __DEV__) {
          logInfo('workout_performance', 'execution_start', {
            timestampMs: Date.now(),
            sessionIndex,
          });
        }
        const prepared = startPreparationRef.current?.key === `${uid}:${executionScopeId}`
          ? startPreparationRef.current
          : null;
        const preflightStartedAtMs = Date.now();
        const [legacyInProgressExecutionIds, permanentPreferences] = await Promise.all([
          prepared?.latestLegacyIds
            ? Promise.resolve(prepared.latestLegacyIds)
            : loadInProgressWorkoutExecutionIds(uid),
          prepared?.latestPreferences
            ? Promise.resolve(prepared.latestPreferences)
            : loadPermanentExerciseSubstitutionPreferences(uid).catch(() => new Map<string, string>()),
        ]);
        if (typeof __DEV__ !== 'undefined' && __DEV__) {
          logInfo('workout_performance', 'execution_preflight_end', {
            timestampMs: Date.now(),
            durationMs: Date.now() - preflightStartedAtMs,
            legacySource: prepared?.latestLegacyIds ? 'live-prefetch' : 'confirm-fallback',
            preferencesSource: prepared?.latestPreferences ? 'live-prefetch' : 'confirm-fallback',
          });
        }
        const result = await startOrResumeWorkoutExecution({
          uid,
          program,
          sessionIndex,
          scheduledLocalDate,
          performedLocalDate,
          preparation: {
            legacyInProgressExecutionIds,
            permanentPreferences,
            ...preparation,
          },
        });
        setExecution(result);
        if (result.timestampAuthority === 'SERVER') pendingStartedAtMsRef.current = null;
        if (typeof __DEV__ !== 'undefined' && __DEV__) {
          logInfo('workout_performance', 'execution_ready', {
            timestampMs: Date.now(),
            sessionIndex,
            timestampAuthority: result.timestampAuthority,
          });
        }
        if (result.timestampAuthority === 'LOCAL_UI_PROJECTION') {
          // Canonical server timestamps are useful for later projections, but
          // are not required to mutate an execution whose transaction already
          // committed. Reconcile only timestamp fields so this read can never
          // clobber newer in-session exercise state.
          void loadWorkoutExecution(uid, result.executionId).then((canonical) => {
            if (!canonical) return;
            pendingStartedAtMsRef.current = null;
            setExecution((current) => current?.executionId === canonical.executionId
              ? {
                  ...current,
                  startedAt: canonical.startedAt,
                  createdAt: canonical.createdAt,
                  updatedAt: canonical.updatedAt,
                  timestampAuthority: 'SERVER',
                }
              : current);
          }).catch((error) => {
            logWarn('workout_execution', 'start_timestamp_reconciliation_failed', { error });
          });
        }
        logInfo('workout_execution', 'start_execution_confirmed', {
          sessionIndex,
          durationMs: Date.now() - startedAtMs,
        });
        return { execution: result, error: null };
      } catch (error) {
        logWarn('workout_execution', 'start_failed', {
          error,
          sessionIndex,
          durationMs: Date.now() - startedAtMs,
          firestoreErrorCode: errorCode(error),
          errorClass: errorClass(error),
        });
        setExecution(null);
        pendingStartedAtMsRef.current = null;
        const startError: WorkoutExecutionStartError = error instanceof WorkoutExecutionConflictError
          ? { code: 'CONFLICT', active: error.active }
          : error instanceof WorkoutExecutionLegacyPendingError
            ? { code: 'LEGACY_PENDING', executionIds: error.executionIds }
            : { code: 'UNKNOWN' };
        setStartError(startError);
        return { execution: null, error: startError };
      } finally {
        setStarting(false);
      }
    });
    if (flight.kind === 'reused') {
      logInfo('workout_execution', 'start_single_flight_reused', { sessionIndex });
      return flight.promise;
    }
    if (flight.kind === 'busy') {
      // One hook instance cannot safely represent two different sessions in
      // flight. The server mutex remains the ultimate guard; this prevents a
      // second local request from being sent before it is needed.
      logWarn('workout_execution', 'start_single_flight_rejected', { sessionIndex });
      return Promise.resolve(unknownError);
    }
    return flight.promise;
  }, [uid, program]);

  const start = useCallback((sessionIndex: number, preparation?: {
    manualSubstitutionContext?: ManualSubstitutionUserContext | null;
    manualSubstitutionContextStatus?: 'loading' | 'ready' | 'error';
  }): Promise<WorkoutExecutionStartResult> => {
    const todayLocalDate = localDateInTimezone(new Date(), timezone ?? deviceTimezone());
    return startWithDates({
      sessionIndex,
      scheduledLocalDate: todayLocalDate,
      performedLocalDate: todayLocalDate,
      preparation,
    });
  }, [startWithDates, timezone]);

  const startAdvanced = useCallback((resolution: ScheduleResolution): Promise<WorkoutExecutionStartResult> => {
    const unknownError = { execution: null, error: { code: 'UNKNOWN' as const } };
    if (!program) return Promise.resolve(unknownError);
    const todayLocalDate = localDateInTimezone(new Date(), timezone ?? deviceTimezone());
    const target = advancedWorkoutTarget({
      scheduleMode: program.scheduleMode ?? 'fixed',
      resolution,
      todayLocalDate,
      sessionCount: program.sessions.length,
      hasIncompatibleExecution: starting || execution?.status === 'IN_PROGRESS',
    });
    return target ? startWithDates(target) : Promise.resolve(unknownError);
  }, [execution?.status, program, startWithDates, starting, timezone]);

  const adoptExecution = useCallback((next: PersistedWorkoutExecution) => {
    pendingStartedAtMsRef.current = null;
    mutationQueueRef.current.reset();
    setHasUnreconciledMutations(false);
    setStartError(null);
    setExecution(next);
  }, []);

  const recordSet = useCallback(async (exerciseIndex: number, setIndex: number, weightKg: number | null, actualReps: number | null = null) => {
    if (!uid || !execution) return;
    try {
      await mutationQueueRef.current.enqueue(
        `set:${exerciseIndex}:${setIndex}`,
        async () => {
          await recordSetExecution({ uid, executionId: execution.executionId, exerciseIndex, setIndex, weightKg, actualReps });
          // Keep this projection inside the queued operation so a successful
          // finish-barrier retry projects the same committed status too.
          setExecution((current) => current && current.executionId === execution.executionId ? {
            ...current,
            exercises: current.exercises.map((exercise, index) => index !== exerciseIndex ? exercise : {
              ...exercise,
              sets: exercise.sets.map((set) => set.setIndex !== setIndex ? set : {
                ...set,
                status: 'COMPLETED' as const,
                weightKg,
                actualReps,
                actualDurationSeconds: null,
              }),
            }),
          } : current);
        },
      );
      setHasUnreconciledMutations(mutationQueueRef.current.hasUnreconciledMutations());
      publishWorkoutLoadRefresh(uid, execution.executionId);
    } catch (error) {
      setHasUnreconciledMutations(true);
      logWarn('workout_execution', 'record_set_failed', { error });
    }
  }, [uid, execution]);

  const skipSet = useCallback(async (exerciseIndex: number, setIndex: number) => {
    if (!uid || !execution) return;
    try {
      await mutationQueueRef.current.enqueue(
        `set:${exerciseIndex}:${setIndex}`,
        async () => {
          await skipSetExecution({ uid, executionId: execution.executionId, exerciseIndex, setIndex });
          setExecution((current) => current && current.executionId === execution.executionId ? {
            ...current,
            exercises: current.exercises.map((exercise, index) => index !== exerciseIndex ? exercise : {
              ...exercise,
              sets: exercise.sets.map((set) => set.setIndex !== setIndex ? set : {
                ...set,
                status: 'SKIPPED' as const,
                weightKg: null,
                actualReps: null,
                actualDurationSeconds: null,
              }),
            }),
          } : current);
        },
      );
      setHasUnreconciledMutations(mutationQueueRef.current.hasUnreconciledMutations());
    } catch (error) {
      setHasUnreconciledMutations(true);
      logWarn('workout_execution', 'skip_set_failed', { error });
    }
  }, [uid, execution]);

  const skipExercise = useCallback(async (exerciseIndex: number) => {
    if (!uid || !execution) return;
    try {
      await mutationQueueRef.current.enqueue(
        `exercise:${exerciseIndex}`,
        async () => {
          await skipExerciseExecution({ uid, executionId: execution.executionId, exerciseIndex });
          setExecution((current) => current && current.executionId === execution.executionId ? {
            ...current,
            exercises: current.exercises.map((exercise, index) => index !== exerciseIndex ? exercise : {
              ...exercise,
              sets: exercise.sets.map((set) => set.status === 'PENDING' ? {
                ...set,
                status: 'SKIPPED' as const,
              } : set),
            }),
          } : current);
        },
      );
      setHasUnreconciledMutations(mutationQueueRef.current.hasUnreconciledMutations());
    } catch (error) {
      setHasUnreconciledMutations(true);
      logWarn('workout_execution', 'skip_exercise_failed', { error });
    }
  }, [uid, execution]);

  const finalize = useCallback(async (
    actualCardioDurationSeconds?: number,
    mode: WorkoutFinalizationMode = 'NORMAL',
  ): Promise<
    { ok: true; result: FinalizeWorkoutSessionResult } | { ok: false; error: unknown }
  > => {
    if (!uid || !execution) return { ok: false, error: new Error('no_active_execution') };
    logInfo('workout_execution', 'execution_finalization_started', {
      programId: execution.programId,
      executionId: execution.executionId,
      sessionIndex: execution.sessionIndex,
      mode,
    });
    try {
      const flushStartedAtMs = Date.now();
      logInfo('workout_performance', 'finish_mutation_flush_start', { timestampMs: flushStartedAtMs });
      try {
        await mutationQueueRef.current.flush();
        setHasUnreconciledMutations(false);
        logInfo('workout_performance', 'finish_mutation_flush_end', {
          timestampMs: Date.now(),
          durationMs: Date.now() - flushStartedAtMs,
          success: true,
        });
      } catch (error) {
        logInfo('workout_performance', 'finish_mutation_flush_end', {
          timestampMs: Date.now(),
          durationMs: Date.now() - flushStartedAtMs,
          success: false,
        });
        throw error;
      }
      const result = await finalizeWorkoutSession({
        executionId: execution.executionId,
        ...(mode === 'NORMAL' ? {} : { mode }),
        ...(actualCardioDurationSeconds === undefined ? {} : {
          cardio: { actualDurationSeconds: actualCardioDurationSeconds },
        }),
      });
      setExecution((prev) => {
        if (!prev || prev.executionId !== execution.executionId) return prev;
        const cardio = result.cardioStatus === 'SKIPPED'
          ? { status: 'SKIPPED' as const, reason: 'EARLY_FINISH' as const, skippedAt: null }
          : result.cardioStatus === 'COMPLETED' && actualCardioDurationSeconds !== undefined
            ? { status: 'COMPLETED' as const, actualDurationSeconds: actualCardioDurationSeconds, completedAt: null }
            : prev.cardio;
        return {
          ...prev,
          status: result.executionStatus,
          exercises: sweepPendingSetsToSkipped(prev.exercises),
          cardio,
          completion: result.completion,
          // Mirrors exactly what the server just persisted (`data.mode` on
          // the request this call made) — never inferred from `status`.
          finalizationMode: mode,
          timestampAuthority: 'LOCAL_UI_PROJECTION',
        };
      });
      logInfo('workout_execution', 'execution_finalization_succeeded', {
        programId: execution.programId,
        executionId: execution.executionId,
        sessionIndex: execution.sessionIndex,
        status: result.executionStatus,
        mode,
      });
      return { ok: true, result };
    } catch (error) {
      logWarn('workout_execution', 'execution_finalization_failed', {
        programId: execution.programId,
        executionId: execution.executionId,
        sessionIndex: execution.sessionIndex,
        errorCode: errorCode(error),
        reason: errorReason(error),
        errorClass: errorClass(error),
      });
      return { ok: false, error };
    }
  }, [uid, execution]);

  const abandon = useCallback(async (): Promise<{ ok: true } | { ok: false; error: unknown }> => {
    if (!uid || !execution) return { ok: false, error: new Error('no_active_execution') };
    try {
      await abandonWorkoutExecution(uid, execution.executionId);
      mutationQueueRef.current.reset();
      setHasUnreconciledMutations(false);
      return { ok: true };
    } catch (error) {
      logWarn('workout_execution', 'abandon_failed', { error });
      return { ok: false, error };
    }
  }, [uid, execution]);

  const abandonExecutionById = useCallback(async (executionId: string) => {
    if (!uid) return;
    try {
      await abandonWorkoutExecution(uid, executionId);
      setStartError(null);
    } catch (error) {
      logWarn('workout_execution', 'abandon_by_id_failed', { error });
      throw error;
    }
  }, [uid]);

  const workoutStartedAtMs = execution
    ? execution.timestampAuthority === 'SERVER'
      ? execution.startedAt.toMillis()
      : pendingStartedAtMsRef.current
    : pendingStartedAtMsRef.current;

  return {
    execution, starting, startError, workoutStartedAtMs, hasUnreconciledMutations,
    start, startAdvanced, adoptExecution, recordSet, skipSet, skipExercise, finalize, abandon, abandonExecutionById,
  };
}
